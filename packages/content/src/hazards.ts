import { card, effect as e } from './helpers';
import type { Card, Op } from './schema';
const hazard = (
  id: string,
  name: string,
  timer: number,
  damage: number,
  tags: string[],
  answeredBy: string[],
  ops: Op[] = [],
  extra: Partial<Card['hazard']> = {},
  more: Partial<Card> = {},
) =>
  card(
    id,
    name,
    'hazard',
    tags,
    `${extra.linger ? 'Each Night' : `Timer ${timer}`}: ${damage} damage${ops.length ? ' and an extra effect' : ''}. ${answeredBy.length ? `Answer: ${answeredBy.join(extra.answerMode === 'all' ? ' AND ' : ' or ')}.` : 'Instant.'}`,
    [
      e('onResolve', [
        ...(damage ? [{ op: 'damage' as const, n: damage }] : []),
        ...ops,
      ]),
    ],
    {
      copies: 2,
      hazard: {
        timer,
        answeredBy,
        ...(tags.includes('Passable') ? { passable: true } : {}),
        ...extra,
      },
      ...more,
    },
  );
